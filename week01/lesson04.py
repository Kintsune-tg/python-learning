# Словарь = пары "ключ: значение". Список ищет по номеру, словарь - по имени.
prices = {"яблоко": 100, "груша": 150, "банан": 80}

print(prices["груша"])           # значение по ключу
print(prices.get("киви", 0))     # .get() не падает, если ключа нет (вернёт 0)
prices["киви"] = 200             # добавить новую пару
prices["яблоко"] = 120           # изменить существующую
del prices["банан"]              # удалить
print("груша" in prices)         # проверяется КЛЮЧ, а не значение

for name in prices:                      # по ключам
    print(name)
for name, price in prices.items():       # по парам ключ + значение
    print(f"{name} стоит {price}")
print(prices.keys(), prices.values())

# Шпаргалка методов (чтобы не забывать):
#   d[key]          - значение (ошибка KeyError, если ключа нет)
#   d.get(key, 0)   - значение или запасное (без ошибки)
#   d.items()       - пары (ключ, значение) для цикла
#   d.keys()        - ключи          d.values() - значения
#   key in d        - есть ли ключ
#   len(d)          - сколько пар

