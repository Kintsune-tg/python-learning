# Как работать: сначала ПРЕДСКАЖИ результат в комментарии, потом запусти и сравни.

# ---------------------------------------------------------------
# ТЕОРИЯ: как читать цикл
# ---------------------------------------------------------------
# for X in КОЛЛЕКЦИЯ:
#     тело цикла
#
# Читается так: "для каждого элемента коллекции: положи его в X и выполни тело".
# X - просто имя, ты придумываешь его сам. Хорошее имя = "один элемент" (sale, order, name).
# Внутри тела используй ТО ЖЕ имя, что написал после for.

sales = [100, 200, 300]

for sale in sales:          # на каждом круге sale = 100, потом 200, потом 300
    print(sale)

# Что лежит в переменной цикла, зависит от коллекции:
#   список чисел        -> число
#   список словарей     -> один целый словарь
#   словарь (for k in d)-> ключ
#   d.items()           -> пара: for key, value in d.items()
#   range(3)            -> числа 0, 1, 2

# ---------------------------------------------------------------
# 4 шаблона, на которых держится 90% циклов
# ---------------------------------------------------------------
# 1) СУММА: заводим 0 ДО цикла, прибавляем внутри
total = 0
for sale in sales:
    total = total + sale
print(total)

# 2) СЧЁТЧИК с условием: считаем, сколько элементов подходят
count = 0
for sale in sales:
    if sale > 150:
        count = count + 1
print(count)

# 3) МАКСИМУМ: берём первый элемент, сравниваем с остальными
best = sales[0]
for sale in sales:
    if sale > best:
        best = sale
print(best)

# 4) НОВЫЙ СПИСОК: фильтруем в пустой список через .append()
big = []
for sale in sales:
    if sale > 150:
        big.append(sale)
print(big)

# Главное правило: переменная для накопления (total, count, best, big)
