# ЗАДАНИЕ 9. while (бонус)
# ---------------------------------------------------------------
# while работает, пока условие истинно. Нужно самому менять переменную, иначе цикл бесконечный.
# Пример:
# n = 1
# while n <= 3:
#     print(n)
#     n = n + 1
# Задача: удваивай число 1, пока оно меньше 1000, и печатай каждое значение.

y = 1
while y < 1000:
    print(y)
    y = y * 2